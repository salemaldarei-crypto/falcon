/* ─── Language Engine ──────────────────────────── */
let currentLang = localStorage.getItem('ns_lang') || 'ar';

/** Translate a key, optionally replacing {n} placeholder */
function t(key, name) {
  const tr = TRANSLATIONS[currentLang] || TRANSLATIONS.ar;
  let s = tr[key] ?? TRANSLATIONS.ar[key] ?? key;
  if (name !== undefined) s = s.replace('{n}', name);
  return s;
}

/** Apply all data-i18n attributes and fix direction */
function applyTranslations() {
  const lang = TRANSLATIONS[currentLang] || TRANSLATIONS.ar;
  const isRTL = lang.dir === 'rtl';

  document.documentElement.lang = currentLang;
  document.documentElement.dir  = lang.dir;
  document.body.style.fontFamily = lang.fontFamily;

  // Text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  // Placeholder
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });

  // RTL / LTR sidebar + main area
  const sb  = document.getElementById('sidebar');
  const ma  = document.getElementById('mainArea');
  if (sb) {
    if (isRTL) { sb.style.right = ''; sb.style.left = 'auto'; }
    else       { sb.style.left  = ''; sb.style.right = 'auto'; }
  }

  // Highlight active language button
  document.querySelectorAll('.lang-btn').forEach(b =>
    b.classList.toggle('active', b.dataset.lang === currentLang)
  );
}

/** Switch language */
function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  localStorage.setItem('ns_lang', lang);
  applyTranslations();
  // Refresh dynamic content if app is running
  if (window.SESSION?.user) {
    window.refreshAll?.();
    window.applyRoleUI?.();
  }
}

// Auto-apply on DOM ready
document.addEventListener('DOMContentLoaded', applyTranslations);
